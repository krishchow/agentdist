import { readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import type { StdioServerNode } from "../ir/nodes";
import type { PackTarget } from "./types";

const Options = z.strictObject({
  /** The patch file, which `dsh.bundle.patch` in package.json must point at. */
  file: z.string().default("cordis.patch.yml"),
  /** The npm package the bundle is installed as. Defaults to the name in package.json. */
  npmPackage: z.string().optional(),
});

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;

/**
 * A DeepSeek Harness bundle layer: a Cordis patch that adds one row per MCP server and one skill
 * provider scoped to the package's own skills directory.
 *
 * Rows are inserted, never overrides, so the bundle composes with the rows a profile already has.
 * The skills root is resolved when the profile activates, through the profile directory the
 * package is installed in, because a patch's config values are otherwise literal.
 */
export const dshBundle: PackTarget = {
  id: "dsh-bundle",
  label: "DeepSeek Harness bundle",
  pack(pkg, raw) {
    const options = Options.parse(raw);
    const npmPackage = options.npmPackage ?? packageJsonName(pkg.root);
    if (!npmPackage) throw new Error("dsh-bundle: set npmPackage, or add a package.json with a name");
    const servers = pkg.nodes.filter(
      (n) => n.kind === "mcpServer" && n.transport === "stdio",
    ) as StdioServerNode[];
    const notes = pkg.nodes.flatMap((n) =>
      n.kind === "hook" || (n.kind === "mcpServer" && n.transport === "http")
        ? [
            `${n.kind === "hook" ? "hook" : "remote server"} "${n.name}" is left out: this target writes stdio servers and skills only`,
          ]
        : [],
    );
    const skills = pkg.manifest.skills?.replace(/^\.\//, "").replace(/\/$/, "");

    const lines = [
      `# DeepSeek Harness (DSH) bundle layer for ${npmPackage}.`,
      "# Generated by `agentdist pack` from agentdist.json. Do not edit by hand.",
      "- insert:",
    ];
    for (const server of servers) {
      lines.push(
        `    - id: ${pkg.name}-mcp${servers.length > 1 ? `-${server.name}` : ""}`,
        "      name: '@deepseek-ai/dsh-mcp-client'",
        "      config:",
        `        serverName: ${server.name}`,
        "        transport: stdio",
        `        command: ${server.command}`,
        ...(server.args.length
          ? ["        args:", ...server.args.map((arg) => `          - ${quote(arg)}`)]
          : []),
        ...(Object.keys(server.env).length
          ? ["        env:", ...Object.entries(server.env).map(([k, v]) => `          ${k}: ${quote(v)}`)]
          : []),
        "        failOnStartupError: true",
        "",
      );
    }
    if (skills) {
      const path = "process.getBuiltinModule('node:path')";
      const resolve = `process.getBuiltinModule('node:module').createRequire(new URL('resolve.mjs', baseUrl)).resolve('${npmPackage}/package.json')`;
      lines.push(
        `    - id: ${pkg.name}-skills`,
        "      name: '@deepseek-ai/dsh-skill-filesystem'",
        "      config:",
        `        providerName: ${pkg.name}`,
        "        includeDefaultRoots: false",
        "        watch: false",
        `        bundledSkillDir: !!js ${path}.join(${path}.dirname(${resolve}), ${skills
          .split("/")
          .map((part) => `'${part}'`)
          .join(", ")})`,
        "",
      );
    }
    return { files: [{ path: options.file, content: `${lines.join("\n").trimEnd()}\n` }], notes };
  },
};

function packageJsonName(root: string): string | undefined {
  try {
    const name = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).name;
    return typeof name === "string" ? name : undefined;
  } catch {
    return undefined;
  }
}
