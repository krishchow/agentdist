// Write docs/harnesses.md from the harness registry, by planning a package that has one of
// everything on a fictional machine and recording where each harness puts it.
import { writeFileSync } from "node:fs";
import { HARNESSES, loadPackage, planInstall } from "../dist/index.js";

const env = { home: "/home/u", projectRoot: "/home/u/repo", vars: {}, platform: "linux" };
const pkg = loadPackage(new URL("../test/fixtures/demo", import.meta.url).pathname);
const KINDS = [
  ["skill", "Skills"],
  ["agent", "Subagents"],
  ["command", "Commands"],
  ["mcpServer", "MCP server"],
];
const show = (path, scope) =>
  scope === "local" ? path.replace(`${env.projectRoot}/`, "") : path.replace(env.home, "~");

function cell(harness, kind, scope) {
  const plan = planInstall(pkg, [harness], scope, env);
  const ops = [...plan.files, ...plan.configs].filter((op) => op.claims[0].node.startsWith(`${kind}:`));
  if (ops.length === 0) return "—";
  const op = ops.find((o) => o.path.endsWith("SKILL.md")) ?? ops[0];
  if (op.type === "config") return `\`${show(op.path, scope)}\` → \`${op.keyPath.slice(0, -1).join(".")}\``;
  // Show the directory, not the fixture's file.
  const dir = show(op.path, scope).replace(/\/demo-[^/]+(\/.*)?$/, "");
  return `\`${dir}\``;
}

const lines = [
  "# Harnesses",
  "",
  "Generated by `scripts/gen-harness-table.mjs` from `src/harnesses`. Do not edit by hand.",
  "",
  "Where each harness gets each kind of artifact. A dash means the harness has no such surface at",
  "that scope, and an install says so instead of guessing. The reasons, and the documentation each",
  "path was checked against, are in the harness's file.",
  "",
];
for (const [scope, title] of [
  ["user", "User scope (`--user`)"],
  ["local", "Repository scope (`--local`)"],
]) {
  lines.push(`## ${title}`, "", `| Harness | id | ${KINDS.map(([, label]) => label).join(" | ")} |`, `|---|---|${KINDS.map(() => "---").join("|")}|`);
  for (const harness of HARNESSES) {
    lines.push(`| ${harness.label} | \`${harness.id}\` | ${KINDS.map(([kind]) => cell(harness, kind, scope)).join(" | ")} |`);
  }
  lines.push("");
}
lines.push("## How each harness names things", "", "| Harness | An MCP tool | Invoking a skill |", "|---|---|---|");
for (const harness of HARNESSES) {
  lines.push(`| ${harness.label} | ${harness.dialect.toolRef("server", "tool")} | ${harness.dialect.skillRef("name")} |`);
}
lines.push(
  "",
  "Content in the shared `.agents/skills` directory is rendered in a portable dialect instead (the",
  "tool and its server named in prose), because no one harness's identifier is right for all of its",
  "readers.",
  "",
);
writeFileSync(new URL("../docs/harnesses.md", import.meta.url), lines.join("\n"));
